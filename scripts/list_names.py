#!/usr/bin/env python3
"""Extract every person-like name used by the dataset and seed data for a coincidence review.

Standard library only. Writes docs/name-review.md. The review notes below were written by hand
(see the method note in the generated file); the script only joins them with the extracted list.
"""
from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]

DATASET = "v1.2"

# Hand-written review notes. "flag" = matches or closely resembles a widely known public figure.
REVIEW = {
    "Alex Rivera": ("note", "Same name as a film director; a common name."),
    "Sam Lee": ("note", "Very common name; also the name of a Hong Kong actor/singer."),
    "Aiden Farrell": ("ok", "Sound-alike spelling pair of Aidan Farrell. No obvious match."),
    "John Parke": ("ok", "Sounds like the existing \"Jon Park\" by design. No widely known person of this exact name known; it "
                         "resembles the first and middle names of the 18th-century John Parke Custis, which is not the same name."),
    "髙木 慎吾": ("ok", "Uses the 髙 / 高 variant by design. No obvious match with a widely known public figure."),
}
RENAMED_BEFORE_PUBLICATION = 6
APP_NAMES = {"Relay": "Generic word; used as the fictional messages app's display name.",
             "Orbit Calendar": "Fictional calendar app's display name; not checked against app stores."}


def names():
    rows = {}
    for app in ("messages", "calendar"):
        cat = json.loads((ROOT / "dataset" / DATASET / "entities" / f"{app}.json").read_text(encoding="utf-8"))
        for e in cat["entities"]:
            if e["type"] == "ContactEntity":
                rows.setdefault(e["forms"][0]["text"], set()).add("contact")
            elif e["type"] == "EventEntity":
                m = re.match(r"^([A-Z][a-z]+)'s ", e["forms"][0]["text"])
                if m:
                    rows.setdefault(m.group(1), set()).add("event title owner")
    gen = (ROOT / "dataset" / "generate.py").read_text(encoding="utf-8")
    inv = re.search(r"INVITEES = \{\"en-US\": \[(.*?)\], \"ja-JP\": \[(.*?)\]\}", gen, re.S)
    for group in inv.groups():
        for n in re.findall(r"\"([^\"]+)\"", group):
            rows.setdefault(n, set()).add("invitee")
    return rows


def main():
    rows = names()
    flagged = {k: v for k, v in REVIEW.items() if k in rows and v[0] == "flag"}
    out = ["# Name coincidence review", "",
           "<!-- Generated by scripts/list_names.py; review notes are maintained in that script. -->", "",
           "Every person-like name used in the synthetic data (contacts, people named in event titles, invitees) and the",
           "fictional app names. All of them were invented for this benchmark and are used only as fictional data.",
           "登場する人名・組織名はすべて架空の合成データであり、実在の人物・団体とは関係ありません。", "",
           f"**Method.** Names were extracted from `dataset/{DATASET}/entities/*.json` and `dataset/generate.py`",
           "(`python3.12 scripts/list_names.py`). Each was reviewed by the assistant from general knowledge for an *obvious*",
           "match with a widely known public figure; no web search was run. Common names match many private people, which",
           "is unavoidable and not flagged.", "",
           f"Result ({DATASET}): {len(rows)} names reviewed, {len(flagged)} flagged as matching a well-known public figure.", "",
           "| Name | Used as | Review | Note |", "|---|---|---|---|"]
    for name in sorted(rows):
        status, note = REVIEW.get(name, ("ok", "No obvious match with a widely known public figure."))
        out.append(f"| {name} | {', '.join(sorted(rows[name]))} | {status} | {note} |")
    out += ["", "## App names", "", "| Name | Note |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in APP_NAMES.items()]
    out += ["", "## Renamed before publication", "",
            f"An earlier review flagged {RENAMED_BEFORE_PUBLICATION} invented names that matched well-known public figures.",
            "They were replaced at the generator level before publication (dataset v1.2), the reference apps' seed data was",
            "regenerated and the affected cases were re-measured; the scores did not change. The re-review of every name in",
            f"v1.2 above found {len(flagged)} matches. Procedure for a future change: edit the names in `dataset/generate.py`,",
            "regenerate the dataset and the seeds (`Apps/tools/make_seed.py`), re-measure the affected cases, then re-run",
            "this script and review the list."]
    (ROOT / "docs" / "name-review.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/name-review.md ({len(rows)} names, {len(flagged)} flagged)")


if __name__ == "__main__":
    main()
