#!/usr/bin/env python3
"""Generate the reference apps' seed data (Swift) from the synthetic dataset catalogs.

Standard library only. Reads dataset/<version>/entities/{messages,calendar}.json (default v1.2) and writes
Apps/Messages/Shared/SeedData.swift and Apps/Calendar/Shared/SeedData.swift. Every value is the
invented data of the benchmark catalog; no real personal data is involved.

`phonetic` is the app-side "pronunciation" field (like a contact's phonetic name): the kana
reading for Japanese entries and a Soundex key sequence for English ones. Apps use it only to
notice sound-alike collisions before acting.
"""
from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
VERSION = None
DEFAULT_DATASET = "v1.2"


def soundex(word):
    letters = [c for c in word.lower() if "a" <= c <= "z"]
    if not letters:
        return word
    codes = {**dict.fromkeys("bfpv", "1"), **dict.fromkeys("cgjkqsxz", "2"), **dict.fromkeys("dt", "3"),
             "l": "4", **dict.fromkeys("mn", "5"), "r": "6"}
    out, last = letters[0].upper(), codes.get(letters[0])
    for c in letters[1:]:
        d = codes.get(c)
        if d and d != last:
            out += d
        if c not in "hw":
            last = d
        if len(out) == 4:
            break
    return out.ljust(4, "0")


def tokens(text):
    text = re.sub(r"['’]s\b", "", text.lower()).replace("'", "").replace("-", "")
    return re.findall(r"[a-z0-9]+", text)


def kana(text):
    out = []
    for ch in text:
        o = ord(ch)
        out.append(chr(o - 0x60) if 0x30A1 <= o <= 0x30F6 else ch)
    return "".join(out).replace(" ", "")


def is_ja(text):
    return any(0x3040 <= ord(c) <= 0x30FF or 0x4E00 <= ord(c) <= 0x9FFF for c in text)


def phonetic(form):
    if is_ja(form["text"]):
        return kana(form.get("reading") or form["text"])
    return " ".join(soundex(t) for t in tokens(form["text"]))


def s(v):
    return json.dumps(v, ensure_ascii=False)


def arr(values):
    return "[" + ", ".join(s(v) for v in values) + "]"


HEADER = "// GENERATED by Apps/tools/make_seed.py from dataset/{version}/entities — do not edit.\n// All names and texts are synthetic benchmark data.\n\n"


def messages(catalog):
    by_type = {}
    for e in catalog["entities"]:
        by_type.setdefault(e["type"], []).append(e)
    lines = [HEADER.format(version=VERSION), "enum SeedData {\n", "    static let contacts: [SeedContact] = [\n"]
    for e in by_type["ContactEntity"]:
        f = e["forms"]
        lines.append(f"        SeedContact(id: {s(e['id'])}, name: {s(f[0]['text'])}, aliases: {arr([x['text'] for x in f[1:]])}, "
                     f"readings: {arr([x['reading'] for x in f if x.get('reading')])}, phonetic: {arr(sorted({phonetic(x) for x in f}))}),\n")
    lines.append("    ]\n\n    static let messages: [SeedMessage] = [\n")
    for e in by_type["MessageEntity"]:
        lines.append(f"        SeedMessage(id: {s(e['id'])}, sender: {s(e['related']['sender'])}, text: {s(e['forms'][0]['text'])}),\n")
    lines.append("    ]\n}\n")
    return "".join(lines)


def calendar(catalog):
    lines = [HEADER.format(version=VERSION), "enum SeedData {\n", "    static let calendars: [SeedCalendar] = [\n"]
    events = [e for e in catalog["entities"] if e["type"] == "EventEntity"]
    for e in catalog["entities"]:
        if e["type"] == "CalendarEntity":
            lines.append(f"        SeedCalendar(id: {s(e['id'])}, title: {s(e['forms'][0]['text'])}, aliases: {arr([x['text'] for x in e['forms'][1:]])}),\n")
    lines.append("    ]\n\n    static let events: [SeedEvent] = [\n")
    for e in events:
        f = e["forms"]
        start = f"{e['attrs']['date']}T{e['attrs']['time']}:00Z"
        lines.append(f"        SeedEvent(id: {s(e['id'])}, title: {s(f[0]['text'])}, aliases: {arr([x['text'] for x in f[1:]])}, "
                     f"readings: {arr([x['reading'] for x in f if x.get('reading')])}, phonetic: {arr(sorted({phonetic(x) for x in f}))}, "
                     f"start: {s(start)}, calendar: {s(e['related']['calendar'])}),\n")
    lines.append("    ]\n}\n")
    return "".join(lines)


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--apps-root", default=str(ROOT / "Apps"), help="write <root>/{Messages,Calendar}/Shared/SeedData.swift")
    ap.add_argument("--dataset", default=DEFAULT_DATASET, help="catalog version (v1.1 reproduces the Phase 3 seeds)")
    args = ap.parse_args(argv)
    global VERSION
    VERSION = args.dataset
    CATALOGS = ROOT / "dataset" / VERSION / "entities"
    root = pathlib.Path(args.apps_root)
    out = {
        root / "Messages" / "Shared" / "SeedData.swift": messages(json.loads((CATALOGS / "messages.json").read_text(encoding="utf-8"))),
        root / "Calendar" / "Shared" / "SeedData.swift": calendar(json.loads((CATALOGS / "calendar.json").read_text(encoding="utf-8"))),
    }
    for path, text in out.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
